type Extra = Partial<Pick<EnglishQuestion, "display" | "hint" | "speak">>;
type Difficulty = EnglishQuestion["difficulty"];

/** Stable small number from an id, so option order doesn't change between builds. */
function seed(id: string) {
  let h = 0;
  for (const c of id) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return h;
}

/** Options are written with the right one first; it lands at a varied position. */
function choice(
  id: string,
  unitId: string,
  skill: EnglishSkill,
  difficulty: Difficulty,
  prompt: string,
  [correct, ...wrong]: string[],
  explanation: string,
  extra: Extra = {},
): EnglishQuestion {
  const correctIndex = seed(id) % (wrong.length + 1);
  const options = [...wrong];
  options.splice(correctIndex, 0, correct);
  return { id, unitId, skill, difficulty, prompt, explanation, verified: false, ...extra, kind: "choice", options, correctIndex };
}

function text(
  id: string,
  unitId: string,
  skill: EnglishSkill,
  difficulty: Difficulty,
  prompt: string,
  acceptedAnswers: string[],
  explanation: string,
  extra: Extra = {},
): EnglishQuestion {
  return { id, unitId, skill, difficulty, prompt, explanation, verified: false, ...extra, kind: "text", acceptedAnswers };
}

function order(
  id: string,
  unitId: string,
  difficulty: Difficulty,
  words: string[],
  acceptedAnswers: string[],
  explanation: string,
): EnglishQuestion {
  return {
    id,
    unitId,
    skill: "grammar",
    difficulty,
    prompt: "Put the words in the right order.",
    explanation,
    verified: false,
    kind: "order",
    words,
    acceptedAnswers,
  };
}

